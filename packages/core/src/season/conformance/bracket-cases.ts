/**
 * The bracket conformance corpus — the shared spec for two implementations of
 * the playoff ladder.
 *
 * Same argument as `cases.ts`, one step further down the chain that decides who
 * is paid. `computeStandings` produces the seeds; `buildBracket` turns the seeds
 * and the playoff scores into a champion and a runner-up, which between them
 * hold 90% of the default payout. Settlement cannot call TypeScript, so the walk
 * has to exist twice — and **two implementations of one rule is the failure that
 * pays the wrong person while every test is green.**
 *
 * Neither side is the authority. `bracket-corpus.json` is, it is generated by
 * running `buildBracket`, and both consume it.
 *
 * ## What is pinned, and what deliberately is not
 *
 * Pinned: every game's pairing, its winner, whether a tie sent the higher seed
 * through, which teams took a bye, who survived each round, and the three
 * outcomes settlement reads — champion, runner-up, third place.
 *
 * Not pinned: `label`. "Semifinal" and "Quarterfinal" exist to render a screen,
 * and requiring the on-chain kernel to carry strings to satisfy a conformance
 * test would put display text in a program that has no display.
 *
 * ## The cases are chosen for where a reimplementation goes wrong
 *
 * Not for coverage of the happy path, which one fixture would give. Each case
 * says why it exists, and the `why` is carried into the JSON so the Rust side
 * reads it too.
 */

