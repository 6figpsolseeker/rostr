export interface BracketCase {
  readonly name: string;
  readonly why: string;
  /** The field in seed order, best first. Seeds are positions in this array. */
  readonly field: readonly string[];
  readonly weeks: readonly number[];
  readonly firstRoundByes: number;
  readonly results: readonly MatchupResult[];
  readonly thirdPlace: boolean;
}

/** A played game. Points are milli-points, as everywhere else. */
const game = (
  week: number,
  home: string,
  away: string,
  homeMilliPoints: number,
  awayMilliPoints: number,
): MatchupResult => ({
  week,
  homeTeamId: home,
  awayTeamId: away,
  homeMilliPoints,
  awayMilliPoints,
});

